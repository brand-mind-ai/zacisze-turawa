function normalizeText(value) {
  return (value ?? "")
    .replace(/\u00a0/g, " ")
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/[ \t]{2,}/g, " ")
    .trim();
}

function unique(values) {
  return [...new Set(values.filter(Boolean))];
}

function toAbsoluteUrl(value, baseUrl) {
  if (!value) return null;
  const cleaned = value.trim();
  if (!cleaned || cleaned.startsWith("data:") || cleaned.startsWith("javascript:")) {
    return null;
  }
  if (cleaned.startsWith("http://https://")) {
    return cleaned.replace("http://https://", "https://");
  }
  if (cleaned.startsWith("//")) {
    return `https:${cleaned}`;
  }
  try {
    return new URL(cleaned, baseUrl).toString();
  } catch {
    return null;
  }
}

function normalizeInternalUrl(value, baseUrl) {
  const absolute = toAbsoluteUrl(value, baseUrl);
  if (!absolute) return null;
  const url = new URL(absolute);
  if (url.origin !== SITE_ORIGIN) return null;
  if (url.pathname.match(MEDIA_PATH_PATTERN)) {
    return null;
  }
  url.hash = "";
  return url.toString();
}

function pathFromUrl(url) {
  return new URL(url).pathname || "/";
}

