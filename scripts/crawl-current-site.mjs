function collectionForPath(routePath, locale) {
  if (locale !== "pl") return `${locale}/pages`;
  if (polishRoomPaths.has(routePath)) return "pl/rooms";
  if (polishOfferPaths.has(routePath)) return "pl/offers";
  return "pl/pages";
}

function pageTypeForPath(routePath, locale) {
  if (locale !== "pl") return "page";
  if (polishRoomPaths.has(routePath)) return routePath === "/pokoje" ? "rooms-index" : "room";
  if (polishOfferPaths.has(routePath)) {
    return routePath === "/pakiety_pobytowe" ? "offers-index" : "offer";
  }
  if (routePath.includes("rezerwacja")) return "booking";
  if (routePath === "/galeria") return "gallery";
  if (routePath === "/kontakt") return "contact";
  return "page";
}

function slugForPath(routePath) {
  if (routePath === "/" || routePath === "/en" || routePath === "/de") return "index";
  return routePath.replace(/^\/+/, "").replace(/[^a-zA-Z0-9_-]+/g, "-");
}

function fileNameFromImageUrl(url, index) {
  const parsed = new URL(url);
  const base = path.basename(parsed.pathname).replace(/[^a-zA-Z0-9._-]/g, "-") || "image";
  const extension = path.extname(base) || ".jpg";
  const stem = path.basename(base, extension);
  return `${String(index + 1).padStart(3, "0")}-${stem}${extension}`.toLowerCase();
}

function isUiImageUrl(url) {
  return UI_IMAGE_PATTERN.test(url);
}

function yamlString(value) {
  return JSON.stringify(value ?? "");
}

function frontmatterArray(values, indent = "") {
  if (!values.length) return `${indent}[]`;
  return values.map((value) => `${indent}- ${yamlString(value)}`).join("\n");
}

async function exists(filePath) {
  try {
    await stat(filePath);
    return true;
  } catch {
    return false;
  }
}

async function writeGenerated(filePath, content) {
  const finalContent = content.includes(GENERATED_MARKER)
    ? content
    : `${GENERATED_MARKER}\n${content}`;

  if (await exists(filePath)) {
    const existing = await readFile(filePath, "utf8");
    if (!force && !existing.includes(GENERATED_MARKER)) {
      throw new Error(`Refusing to overwrite non-generated file: ${filePath}`);
    }
  }
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, finalContent, "utf8");
}

async function writeGeneratedJson(filePath, value) {
  if (await exists(filePath)) {
    const existing = await readFile(filePath, "utf8");
    if (!force && !existing.includes('"generatedBy": "scripts/crawl-current-site.mjs"')) {
      throw new Error(`Refusing to overwrite non-generated JSON file: ${filePath}`);
    }
  }
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(
    filePath,
    `${JSON.stringify(
      {
        generatedBy: "scripts/crawl-current-site.mjs",
        generatedAt: new Date().toISOString(),
        ...value,
      },
      null,
      2,
    )}\n`,
    "utf8",
  );
}

async function fetchBuffer(url) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);
  try {
    const response = await fetch(url, {
      headers: { "user-agent": "Codex Zacisze migration crawler" },
      signal: controller.signal,
    });
    const arrayBuffer = await response.arrayBuffer();
    return {
      ok: response.ok,
      status: response.status,
      contentType: response.headers.get("content-type") ?? "",
      buffer: Buffer.from(arrayBuffer),
    };
  } finally {
    clearTimeout(timeout);
  }
}

async function fetchText(url) {
  const fetched = await fetchBuffer(url);
  return {
    ...fetched,
    text: fetched.buffer.toString("utf8"),
  };
}

async function fetchSitemapUrls() {
  const sitemap = await fetchText(SITEMAP_URL);
  if (!sitemap.ok) {
    throw new Error(`Failed to fetch sitemap: ${SITEMAP_URL} status ${sitemap.status}`);
  }
  const $ = cheerio.load(sitemap.text, { xmlMode: true });
  return $("url loc")
    .map((_, element) => $(element).text().trim())
    .get()
    .filter((url) => url.startsWith(SITE_ORIGIN));
}

function extractLinks($, baseUrl) {
  return unique(
    $("a[href]")
      .map((_, element) => normalizeInternalUrl($(element).attr("href"), baseUrl))
      .get(),
  );
}

function extractImages($, baseUrl, routePath) {
  const candidates = [];

  $("meta[property='og:image'], meta[name='twitter:image']").each((_, element) => {
    candidates.push({
      source: "meta",
      value: $(element).attr("content"),
      alt: "",
      context: "head",
    });
  });

  $("img").each((_, element) => {
    const el = $(element);
    for (const attribute of ["src", "data-src", "data-lazy", "data-original"]) {
      candidates.push({
        source: attribute,
        value: el.attr(attribute),
        alt: normalizeText(el.attr("alt")),
        width: el.attr("width") ?? "",
        height: el.attr("height") ?? "",
        context: normalizeText(el.closest("section, article, div").attr("class") ?? ""),
      });
    }
    const srcset = el.attr("srcset") ?? el.attr("data-srcset");
    if (srcset) {
      for (const part of srcset.split(",")) {
        candidates.push({
          source: "srcset",
          value: part.trim().split(/\s+/)[0],
          alt: normalizeText(el.attr("alt")),
          width: el.attr("width") ?? "",
          height: el.attr("height") ?? "",
          context: normalizeText(el.closest("section, article, div").attr("class") ?? ""),
        });
      }
    }
  });

  $("[style*='background']").each((_, element) => {
    const style = $(element).attr("style") ?? "";
    const matches = [...style.matchAll(/url\((['"]?)(.*?)\1\)/gi)];
    for (const match of matches) {
      candidates.push({
        source: "background",
        value: match[2],
        alt: "",
        context: normalizeText($(element).attr("class") ?? ""),
      });
    }
  });

  const seen = new Set();
  return candidates
    .map((image, index) => {
      const absoluteUrl = toAbsoluteUrl(image.value, baseUrl);
      if (!absoluteUrl || seen.has(absoluteUrl)) return null;
      seen.add(absoluteUrl);
      return {
        index,
        routePath,
        absoluteUrl,
        source: image.source,
        alt: image.alt ?? "",
        width: image.width ?? "",
        height: image.height ?? "",
        context: image.context ?? "",
      };
    })
    .filter(Boolean);
}

function extractPageText($) {
  const copy = cheerio.load($.html());
  copy("script, style, noscript, svg, iframe, form").remove();
  copy(
    "header, nav, footer, .mainHeader, .mobileBar, #mobileMenu, .bottomNavMobile, .CookieModal, #cookieWarning, #cookiesSettingsModal, .cookiesSettingsModalWindow, .smallcookie, .preloader, .langs, .socialMedia, [class*='ookie'], [id*='ookie']",
  ).remove();

  const blocks = [];
  copy("h1,h2,h3,h4,h5,h6,p,li").each((_, element) => {
    const text = normalizeText(copy(element).text());
    if (text && text.length > 1) blocks.push(text);
  });

  return unique(blocks);
}

function markdownFromBlocks(blocks) {
  if (!blocks.length) return "_No visible body text extracted. Verify manually._";
  return blocks
    .map((block) => {
      if (block.length <= 90 && !block.includes(".") && !block.includes(",")) {
        return `## ${block}`;
      }
      return block;
    })
    .join("\n\n");
}

function extractPage(url, status, contentType, html) {
  const routePath = pathFromUrl(url);
  const locale = localeForPath(routePath);
  const $ = cheerio.load(html);
  const title = normalizeText($("title").first().text());
  const seoDescription = normalizeText($("meta[name='description']").attr("content"));
  const h1 = normalizeText($("h1").first().text());
  const headings = $("h1,h2,h3,h4")
    .map((_, element) => ({
      level: element.tagName.toLowerCase(),
      text: normalizeText($(element).text()),
    }))
    .get()
    .filter((heading) => heading.text);

  const images = extractImages($, url, routePath);
  const links = extractLinks($, url);
  const textBlocks = extractPageText($);

  return {
    url,
    routePath,
    status,
    contentType,
    locale,
    collection: collectionForPath(routePath, locale),
    pageType: pageTypeForPath(routePath, locale),
    slug: slugForPath(routePath),
    title: h1 || title || routePath,
    seoTitle: title,
    description: seoDescription,
    headings,
    images,
    links,
    textBlocks,
  };
}

async function crawl() {
  const sitemapUrls = await fetchSitemapUrls();
  const queue = [...sitemapUrls];
  const queued = new Set(queue);
  const pages = [];
  const nonHtml = [];

  for (let cursor = 0; cursor < queue.length && cursor < MAX_INTERNAL_PAGES; cursor += 1) {
    const url = queue[cursor];
    if (cursor % 10 === 0) {
      console.error(`Crawling ${cursor + 1}/${queue.length}: ${url}`);
    }

    let fetched;
    try {
      fetched = await fetchText(url);
    } catch (error) {
      nonHtml.push({
        url,
        routePath: pathFromUrl(url),
        status: 0,
        contentType: "",
        error: error.message,
      });
      continue;
    }
    const isHtml = fetched.contentType.includes("text/html");

    if (!isHtml) {
      nonHtml.push({
        url,
        routePath: pathFromUrl(url),
        status: fetched.status,
        contentType: fetched.contentType,
      });
      continue;
    }

    const page = extractPage(url, fetched.status, fetched.contentType, fetched.text);
    pages.push(page);

    for (const link of page.links) {
      if (!queued.has(link) && new URL(link).origin === SITE_ORIGIN) {
        queued.add(link);
        queue.push(link);
      }
    }
  }

  return { sitemapUrls, discoveredUrls: [...queued], pages, nonHtml };
}

async function downloadImages(pages) {
  const imageMap = [];
  const seen = new Map();

  for (const page of pages) {
    const downloadable = page.images.filter((image) =>
      image.absoluteUrl.startsWith(SITE_ORIGIN),
    );

    for (let index = 0; index < downloadable.length; index += 1) {
      const image = downloadable[index];
      if (!seen.has(image.absoluteUrl)) {
        if (seen.size % 25 === 0) {
          console.error(`Downloading image ${seen.size + 1}: ${image.absoluteUrl}`);
        }
        const imageName = fileNameFromImageUrl(image.absoluteUrl, seen.size);
        const mediaPath = `/media/current-site/${imageName}`;
        const localPath = path.join(repoRoot, "public", mediaPath);
        try {
          let existingAsset = null;
          try {
            const existing = await stat(localPath);
            if (existing.size > 0) {
              existingAsset = existing;
            }
          } catch {
            // Asset is not already present from a prior run.
          }

          if (existingAsset) {
            seen.set(image.absoluteUrl, {
              mediaPath,
              localPath,
              status: 200,
              contentType: "",
              bytes: existingAsset.size,
            });
          } else {
            const fetched = await fetchBuffer(image.absoluteUrl);
            if (fetched.ok && fetched.buffer.length > 0) {
              await mkdir(path.dirname(localPath), { recursive: true });
              await writeFile(localPath, fetched.buffer);
              seen.set(image.absoluteUrl, {
                mediaPath,
                localPath,
                status: fetched.status,
                contentType: fetched.contentType,
                bytes: fetched.buffer.length,
              });
            } else {
              seen.set(image.absoluteUrl, {
                mediaPath: "",
                localPath: "",
                status: fetched.status,
                contentType: fetched.contentType,
                bytes: 0,
                error: "Image request failed or returned empty body",
              });
            }
          }
        } catch (error) {
          seen.set(image.absoluteUrl, {
            mediaPath: "",
            localPath: "",
            status: 0,
            contentType: "",
            bytes: 0,
            error: error.message,
          });
        }
      }

      imageMap.push({
        ...image,
        ...seen.get(image.absoluteUrl),
      });
    }
  }

  return imageMap;
}

async function writeContentFiles(pages, imageMap) {
  const imageByRoute = new Map();
  for (const image of imageMap) {
    if (!image.mediaPath) continue;
    if (isUiImageUrl(image.absoluteUrl)) continue;
    if (!imageByRoute.has(image.routePath)) imageByRoute.set(image.routePath, []);
    imageByRoute.get(image.routePath).push(image.mediaPath);
  }

  for (const page of pages) {
    const images = unique(imageByRoute.get(page.routePath) ?? []);
    const filePath = path.join(repoRoot, "src/content", page.collection, `${page.slug}.md`);
    const markdown = `---
locale: ${yamlString(page.locale)}
translationKey: ${yamlString(page.slug)}
canonicalPath: ${yamlString(page.routePath)}
sourceUrl: ${yamlString(page.url)}
pageType: ${yamlString(page.pageType)}
title: ${yamlString(page.title)}
seoTitle: ${yamlString(page.seoTitle)}
description: ${yamlString(page.description)}
heroImage: ${yamlString(images[0] ?? "")}
gallery:
${frontmatterArray(images.slice(1), "  ")}
booking:
  enabled: ${page.pageType === "booking" ? "true" : "false"}
  verifiedParamsOnly: true
---

${GENERATED_MARKER}

${markdownFromBlocks(page.textBlocks)}
`;
    await writeGenerated(filePath, markdown);
  }
}

function buildInventoryMarkdown(crawlResult, imageMap) {
  const statusCounts = crawlResult.pages.reduce((acc, page) => {
    acc[page.status] = (acc[page.status] ?? 0) + 1;
    return acc;
  }, {});

  const routeRows = crawlResult.pages
    .map(
      (page) =>
        `| ${page.routePath} | ${page.status} | ${page.locale} | ${page.pageType} | ${page.images.length} | ${page.textBlocks.length} |`,
    )
    .join("\n");

  const nonHtmlRows = crawlResult.nonHtml
    .map((item) => `| ${item.routePath} | ${item.status} | ${item.contentType} |`)
    .join("\n");

  const missingImages = imageMap.filter((image) => !image.mediaPath || image.error);
  const missingImageRows = missingImages
    .slice(0, 100)
    .map(
      (image) =>
        `| ${image.routePath} | ${image.status} | ${image.absoluteUrl} | ${image.error ?? ""} |`,
    )
    .join("\n");

  return `${GENERATED_MARKER}
# Current Site Inventory

Updated: ${new Date().toISOString()}

Source: ${SITE_ORIGIN}

## Summary

- Sitemap URLs: ${crawlResult.sitemapUrls.length}
- Discovered internal URLs: ${crawlResult.discoveredUrls.length}
- HTML pages crawled: ${crawlResult.pages.length}
- Non-HTML sitemap assets: ${crawlResult.nonHtml.length}
- Downloaded/current-site image references: ${imageMap.filter((image) => image.mediaPath).length}
- Failed image references: ${missingImages.length}
- Status counts: ${JSON.stringify(statusCounts)}

## HTML Routes

| Path | Status | Locale | Page type | Image refs | Text blocks |
| --- | ---: | --- | --- | ---: | ---: |
${routeRows}

## Non-HTML Sitemap Items

| Path | Status | Content type |
| --- | ---: | --- |
${nonHtmlRows || "| _None_ |  |  |"}

## Failed Image References

| Path | Status | URL | Error |
| --- | ---: | --- | --- |
${missingImageRows || "| _None_ |  |  |"}
`;
}

